// ============================================================================
// DAILY ROTATION
//
// Days are counted from ROTATION_EPOCH (UTC). The playlist is dealt in decks:
// each deck is a seeded shuffle of the whole list, and each day takes the
// first track in the queue whose source and artist both differ from the day
// before. A skipped track waits for a later day, so no track is lost and two
// consecutive days never share a source or an artist.
// ============================================================================

const ROTATION_EPOCH = Date.UTC(2026, 0, 1);
const DAY_MS = 86_400_000;

/** mulberry32 — small seeded PRNG, deterministic across runtimes. */
function seededRandom(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffledDeck(deck: number): number[] {
  const order = UNDERGROUND_PLAYLIST.map((_, i) => i);
  const rand = seededRandom(0x9e3779b9 ^ (deck + 1));
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}

function clashes(a: YouTubeTrack, b: YouTubeTrack): boolean {
  return a.source === b.source || a.artist === b.artist;
}

// Memoised schedule: rotation[d] is the playlist index for day d.
const rotation: number[] = [];
const queue: number[] = [];
let nextDeck = 0;

function trackIndexForDay(day: number): number {
  while (rotation.length <= day) {
    const prev =
      rotation.length > 0 ? UNDERGROUND_PLAYLIST[rotation[rotation.length - 1]] : null;
    const fits = (i: number) => !prev || !clashes(UNDERGROUND_PLAYLIST[i], prev);
    let pos = queue.findIndex(fits);
    while (pos === -1) {
      queue.push(...shuffledDeck(nextDeck++));
      pos = queue.findIndex(fits);
    }
    rotation.push(queue.splice(pos, 1)[0]);
  }
  return rotation[day];
}

/** Days since ROTATION_EPOCH for the UTC calendar date of `date` (never negative). */
export function rotationDay(date: Date): number {
  const utcMidnight = Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate());
  return Math.max(0, Math.floor((utcMidnight - ROTATION_EPOCH) / DAY_MS));
}

/** Deterministic daily pick for the UTC date of `date` (default: today). */
export function getDailyTrack(date: Date = new Date()): YouTubeTrack {
  return UNDERGROUND_PLAYLIST[trackIndexForDay(rotationDay(date))];
}
